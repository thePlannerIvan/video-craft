#!/usr/bin/env python3
"""Clean the working directory after a delivery is confirmed (Stage 12).

A finished talking-head project left 2.5 GB of `edit/` behind — more than the
source (1.6 GB) and far more than the delivery (723 MB): the per-segment encodes
(`clips_*/`), the lossless concat intermediate (`base.mp4`), test artefacts under
`verify/`, the working render, and regenerable preview/backup files.

What survives is the REBUILDABLE MINIMUM: the files that would cost real work to
recreate (transcripts, the reviewed cut decisions, the article and line plan,
the generated subtitles, the project memory). Everything else is a pure function
of those plus the source media and can be regenerated by re-rendering.

Approval model: the first run only reports. Once a human approves, run with
`--approve` (or `--apply` for a one-off) and the decision is remembered in
`edit/.cleanup-approved`, so later projects apply the same keep-list by default
and just report what they removed — which is what "首次确认，之后默认" means in
practice.

Usage:
  <venv>/python helpers/clean_edit_dir.py <edit_dir>            # report only
  <venv>/python helpers/clean_edit_dir.py <edit_dir> --approve  # remember + apply
  <venv>/python helpers/clean_edit_dir.py <edit_dir> --apply    # apply once
  <venv>/python helpers/clean_edit_dir.py <edit_dir> --json
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

APPROVAL_MARKER = ".cleanup-approved"

# Regenerable from the source media + the kept files below. Matched by name or
# glob, relative to edit/.
DELETE_PATTERNS = [
    "clips_*",              # per-segment encodes (rebuilt by render.py)
    "base*.mp4",            # lossless concat intermediate
    "final*.mp4",           # working render — the delivery copy lives in 成品/
    "preview*.mp4",
    "_concat_*.txt",
    "verify",               # QA clips, probe frames, cross-check audio
    "edl_preview.html",     # rebuilt by edl_preview_build.py
    "edl.prev-*.json",      # ad-hoc backups; edl.previous.json is the rolling one
    "edl.preselection.json", "master.srt",   # both retired 2026-09-15
    "edl.prerangeclean-*.json", "edl.prefiller-*.json",
    "edl.prefix-*.json", "edl.presync-*.json", "edl.presnap-*.json",
    "edl.presync*.json", "edl.prefixframes-*.json",
]

# Cost real work to recreate, or carry a human decision. Never touched.
KEEP_NAMES = [
    "edl.json",                 # the cut (reviewed)
    "edl.previous.json",        # one step back
    "selections.json",          # the user's word-level review decisions
    "transcripts",              # the expensive, immutable ASR cache
    "takes_packed.md",          # the editor's reading view
    "caption_words.json", "captions_article.txt", "semantic_lines.txt",
    "caption_lock.json", "captions.json", "caption_corrections.json",
    "subtitles.srt",
    "project.md",
]


def dir_size(path: Path) -> int:
    if path.is_file():
        return path.stat().st_size
    return sum(p.stat().st_size for p in path.rglob("*") if p.is_file())


def plan(edit_dir: Path, keep_extra: list[str] | None = None
         ) -> tuple[list[tuple[str, int]], list[tuple[str, int]]]:
    """(to_delete, to_keep) with sizes in bytes."""
    keep: set[Path] = set()
    for name in list(keep_extra or []):
        p = edit_dir / name
        if p.exists():
            keep.add(p)
    for name in KEEP_NAMES:
        p = edit_dir / name
        if p.exists():
            keep.add(p)
    delete: list[tuple[str, int]] = []
    seen: set[Path] = set()
    for pattern in DELETE_PATTERNS:
        for p in sorted(edit_dir.glob(pattern)):
            if p in keep or p in seen or not p.exists():
                continue
            seen.add(p)
            delete.append((p.name, dir_size(p)))
    kept = [(p.name, dir_size(p)) for p in sorted(keep)]
    return delete, kept


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("edit_dir", type=Path)
    ap.add_argument("--apply", action="store_true", help="delete now (one-off)")
    ap.add_argument("--approve", action="store_true", help="remember approval, then delete")
    ap.add_argument("--keep", action="append", default=[], metavar="NAME",
                    help="protect an extra path from this run (e.g. the working "
                         "render while a review page still plays from it)")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    edit_dir = args.edit_dir.resolve()
    if not edit_dir.is_dir():
        raise SystemExit(f"not a directory: {edit_dir}")
    marker = edit_dir / APPROVAL_MARKER
    approved_before = marker.exists()
    act = args.apply or args.approve or approved_before

    delete, kept = plan(edit_dir, args.keep)
    freed = sum(size for _, size in delete)

    if args.json:
        print(json.dumps({
            "edit_dir": str(edit_dir),
            "delete": [{"name": n, "bytes": s} for n, s in delete],
            "keep": [{"name": n, "bytes": s} for n, s in kept],
            "freed_bytes": freed,
            "applied": act,
        }, ensure_ascii=False, indent=2))
    else:
        print(f"工作区 {edit_dir}")
        print(f"  将删除 {len(delete)} 项，回收 {freed / 1e6:.1f} MB：")
        for name, size in delete:
            print(f"    - {name:32s} {size / 1e6:8.1f} MB")
        print(f"  保留 {len(kept)} 项（可重建最小集）：")
        for name, size in kept:
            print(f"    + {name:32s} {size / 1e6:8.1f} MB")
        if not act:
            print("  ——未删除（首次需要人工确认：看过清单后加 --approve）")

    if not act:
        return 0
    if args.approve and not approved_before:
        marker.write_text("删中间物、留可重建最小集：用户已确认\n", encoding="utf-8")
        print(f"  已记录批准：{APPROVAL_MARKER}（此后同类项目默认清理）")
    for name, _ in delete:
        target = edit_dir / name
        if target.is_dir():
            shutil.rmtree(target, ignore_errors=True)
        elif target.exists():
            target.unlink()
    print(f"  已回收 {freed / 1e6:.1f} MB；工作区剩余 "
          f"{dir_size(edit_dir) / 1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
