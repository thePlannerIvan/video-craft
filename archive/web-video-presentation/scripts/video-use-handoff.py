"""Assemble a web-video-presentation input/ folder from a video-use edit directory.

The video-use → web-video-presentation handoff contract:

    video-use edit/  ──►  <web_project>/input/
      final.mp4              audio.mp3        (extracted, mp3 192k)
      edl.json               subtitles.srt    (sentence-level, via srt_export)
      transcripts/*.json     assets/frames/   (optional evenly-spaced frames)

The SRT is generated by video-use's srt_export.py (sentence-level, output-
timeline offsets) — never use video-use's caption-optimized master.srt here.

Usage:
    python scripts/video-use-handoff.py <videos_dir> -o <web_project>/input
    python scripts/video-use-handoff.py --edit-dir <edit_dir> -o <web_project>/input
    python scripts/video-use-handoff.py <videos_dir> -o <input> --frames 8
    python scripts/video-use-handoff.py <videos_dir> -o <input> --video-use-dir ~/Developer/video-use
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path


def locate_edit_dir(videos_dir: Path | None, edit_dir: Path | None) -> Path:
    if edit_dir:
        d = edit_dir.resolve()
    elif videos_dir:
        d = (videos_dir / "edit").resolve()
    else:
        sys.exit("need <videos_dir> or --edit-dir")
    if not d.is_dir():
        sys.exit(f"edit directory not found: {d}")
    return d


def extract_audio(video: Path, out_path: Path) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        "ffmpeg", "-y", "-i", str(video),
        "-vn", "-c:a", "libmp3lame", "-b:a", "192k",
        str(out_path),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    print(f"audio → {out_path.name}")


def export_sentence_srt(edit_dir: Path, out_path: Path, video_use_dir: Path) -> None:
    helpers = video_use_dir / "helpers"
    if not (helpers / "srt_export.py").exists():
        sys.exit(f"srt_export.py not found in {helpers} (pass --video-use-dir)")
    sys.path.insert(0, str(helpers))
    from srt_export import build_sentence_srt  # type: ignore

    import json
    edl = json.loads((edit_dir / "edl.json").read_text())
    build_sentence_srt(edl, edit_dir, out_path)


def extract_frames(video: Path, frames_dir: Path, n: int) -> None:
    frames_dir.mkdir(parents=True, exist_ok=True)
    probe = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=noprint_wrappers=1:nokey=1", str(video)],
        capture_output=True, text=True, check=True,
    )
    duration = float(probe.stdout.strip())
    for i in range(n):
        t = duration * (i + 0.5) / n
        out = frames_dir / f"frame_{i + 1:02d}.jpg"
        cmd = [
            "ffmpeg", "-y", "-ss", f"{t:.3f}", "-i", str(video),
            "-frames:v", "1", "-q:v", "4", str(out),
        ]
        subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    print(f"frames → {frames_dir.name}/ ({n} frames)")


def main() -> None:
    ap = argparse.ArgumentParser(description="video-use edit/ → web-video input/ handoff")
    ap.add_argument("videos_dir", type=Path, nargs="?", help="videos directory containing edit/")
    ap.add_argument("-o", "--output", type=Path, required=True, help="target input/ directory")
    ap.add_argument("--edit-dir", type=Path, default=None, help="override edit directory location")
    ap.add_argument("--frames", type=int, default=0, help="extract N evenly-spaced frames into assets/frames/")
    ap.add_argument("--video-use-dir", type=Path, default=Path.home() / "Developer/video-use",
                    help="video-use repo root (for srt_export.py)")
    args = ap.parse_args()

    edit_dir = locate_edit_dir(args.videos_dir, args.edit_dir)
    if not (edit_dir / "edl.json").exists():
        sys.exit(f"no edl.json at {edit_dir}")

    out = args.output.resolve()
    assets = out / "assets"

    # 1. audio — prefer final.mp4, fall back to base.mp4
    final = edit_dir / "final.mp4"
    base = edit_dir / "base.mp4"
    source_video = final if final.exists() else (base if base.exists() else None)
    if source_video is None:
        sys.exit(f"no final.mp4/base.mp4 in {edit_dir}")
    extract_audio(source_video, out / "audio.mp3")

    # 2. sentence-level SRT
    export_sentence_srt(edit_dir, out / "subtitles.srt", args.video_use_dir)

    # 3. optional frames
    if args.frames > 0:
        extract_frames(source_video, assets / "frames", args.frames)

    print(f"\nhandoff complete → {out}")
    print("  audio.mp3 + subtitles.srt" + (" + assets/frames/" if args.frames else ""))


if __name__ == "__main__":
    main()
